#ifndef RANDOM_H
#define RANDOM_H

#define MIN(a, b) ((a) < (b) ? (a) : (b))
#define CEIL(a, b) (((a) / (b)) + ((a) % (b) != 0))

#include <stdint.h>

#define UINT_TYPE(bitsize) uint##bitsize##_t

#define RANDOM_UINT(bitsize, upper_bound, maxLength) \
    do { \
        UINT_TYPE(bitsize) buf[maxLength]; \
        if (random((uint8_t *)buf, sizeof(buf) / sizeof(buf[0]), (uint8_t)((upper_bound) - 1)) != RET_OK) { \
            return 0; \
        } \
        UINT_TYPE(bitsize) result = 0; \
        for (UINT_TYPE(bitsize) i = 0; i < maxLength; i++) { \
            result |= ((UINT_TYPE(bitsize))buf[i]) << (i * 8); \
        } \
        return result; \
    } while(0)

typedef enum {
    RET_OK = 0,
    RET_ERR = -1
} ret_t;

/**
 * @brief Initialize the internal random generator state.
 */
void random_init(void);

/**
 * @brief Generate random bytes.
 * @param[out] buf Output buffer.
 * @param length Number of bytes to generate.
 * @param upper_bound Inclusive upper bound applied to each generated byte.
 * 
 * @return ret_t RET_OK on success, RET_ERR on failure.
 */
ret_t random(uint8_t * buf, uint32_t len, uint8_t upper_bound);

#endif
